// Turns mapshaper output (projected GeoJSON) into src/data/indiaMap.js.
// Usage: node scripts/map/build-india-map.mjs <mapshaper-out-dir> src/data/indiaMap.js
import fs from 'fs';
const dir = process.argv[2], outFile = process.argv[3];
const read = (f) => { const d = JSON.parse(fs.readFileSync(`${dir}/${f}`, 'utf8')); return { features: d.features || d.geometries.map((g) => ({ geometry: g, properties: {} })) }; };
const outline = read('outline.json'), borders = read('borders.json'), cities = read('cities.json');
const pts = [];
const walk = (c) => (typeof c[0] === 'number' ? pts.push(c) : c.forEach(walk));
outline.features.forEach((f) => walk(f.geometry.coordinates));
const minX = Math.min(...pts.map((p) => p[0])), maxX = Math.max(...pts.map((p) => p[0]));
const minY = Math.min(...pts.map((p) => p[1])), maxY = Math.max(...pts.map((p) => p[1]));
const W = 600, s = W / (maxX - minX), H = Math.round((maxY - minY) * s);
const P = ([x, y]) => [+((x - minX) * s).toFixed(0), +((maxY - y) * s).toFixed(0)];
const ring = (r, close) => {
  let prev = null, d = '';
  r.map(P).forEach((p, i) => {
    if (prev && p[0] === prev[0] && p[1] === prev[1]) return;
    d += (i === 0 ? 'M' : 'L') + p[0] + ' ' + p[1];
    prev = p;
  });
  return d + (close ? 'Z' : '');
};
const geomPath = (g, close) => {
  if (g.type === 'Polygon') return g.coordinates.map((r) => ring(r, close)).join('');
  // Largest shape first, so the mainland draws before the islands.
  if (g.type === 'MultiPolygon')
    return [...g.coordinates].sort((a, b) => b[0].length - a[0].length).flatMap((p) => p.map((r) => ring(r, close))).join('');
  if (g.type === 'LineString') return ring(g.coordinates, false);
  if (g.type === 'MultiLineString') return g.coordinates.map((r) => ring(r, false)).join('');
  return '';
};
const outlineD = outline.features.map((f) => geomPath(f.geometry, true)).join('');
const bordersD = borders.features.map((f) => geomPath(f.geometry, false)).join('');
const places = Object.fromEntries(
  cities.features.map((f) => {
    const [x, y] = P(f.geometry.coordinates);
    return [f.properties.id, { x: +((x / W) * 100).toFixed(2), y: +((y / H) * 100).toFixed(2) }];
  })
);
const src = `// GENERATED by scripts/map/build-india-map.mjs (see scripts/map/README.md). Do not edit by hand.
// Source: DataMeet India community, "India states" (github.com/datameet/maps), CC BY 4.0.
// Outer boundary follows the official Survey of India depiction. Simplified with
// mapshaper (1.2%), Lambert conformal conic projection (lat 12/28, lon 80).
// Known limitation: the state layer predates 2019, so the J&K / Ladakh UT line is not drawn.
export const MAP_VIEWBOX = '0 0 ${W} ${H}';
export const MAP_RATIO = ${(H / W).toFixed(4)};
export const OUTLINE_PATH = '${outlineD}';
export const BORDERS_PATH = '${bordersD}';
// Marker positions as % of the map box, projected with the same transform.
export const PLACES = ${JSON.stringify(places, null, 2)};
`;
fs.writeFileSync(outFile, src);
console.log(W, H, 'bytes', src.length);
